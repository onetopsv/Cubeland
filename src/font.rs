/// Chiều rộng chữ tính theo "ô" (mỗi ký tự 5 ô + 1 ô cách).
pub fn text_width_units(text: &str) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        n * 6 - 1
    }
}

/// Chia chữ thành các đoạn ngang liền nhau: (x, y, độ dài) theo đơn vị ô.
/// Gộp theo hàng để giảm số hình chữ nhật phải vẽ.
pub fn text_runs(text: &str) -> Vec<(u32, u32, u32)> {
    let mut runs = Vec::new();
    for (ci, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            let mut x = 0;
            while x < 5 {
                if bits & (1 << (4 - x)) != 0 {
                    let start = x;
                    while x < 5 && bits & (1 << (4 - x)) != 0 {
                        x += 1;
                    }
                    runs.push((ci as u32 * 6 + start, row as u32, x - start));
                } else {
                    x += 1;
                }
            }
        }
    }
    runs
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn width_of_text() {
        assert_eq!(text_width_units(""), 0);
        assert_eq!(text_width_units("A"), 5);
        assert_eq!(text_width_units("AB"), 11);
    }

    #[test]
    fn letter_i_runs() {
        // I: hàng 0 và 6 rộng 3 ô (x=1..3), các hàng giữa 1 ô ở x=2
        let r = text_runs("I");
        assert_eq!(r.len(), 7);
        assert!(r.contains(&(1, 0, 3)));
        assert!(r.contains(&(2, 3, 1)));
    }

    #[test]
    fn runs_stay_inside_text_box() {
        let t = "OPTI-ZOOM 0123456789 ^~<>*";
        let w = text_width_units(t);
        for (x, y, l) in text_runs(t) {
            assert!(x + l <= w && y < 7 && l >= 1);
        }
    }

    #[test]
    fn all_labels_have_glyphs() {
        for c in "DEBUGCHATKEYBOARDTABOPTI-ZOOM3RDMOUSEPRISEGUINVJUMPESC^<>~*PAUSED".chars() {
            assert_ne!(glyph(c), [0; 7], "thiếu glyph cho {:?}", c);
        }
    }

    #[test]
    fn lowercase_maps_to_uppercase() {
        assert_eq!(glyph('a'), glyph('A'));
    }
}
